alter table _archivo add column clave text;
update _archivo set clave = regexp_replace(translate(lower(nombre), 'áéíóúüñàèìòùâêîôû', 'aeiouunaeiouaeiou'), '[^a-z0-9]', '', 'g');

-- Producto existente para cada renglón: primero por código, luego por nombre.
create temp table _cruce on commit drop as
select a.codigo, a.nombre,
       coalesce(
         (select p.id from productos p where p.codigo_barras = a.codigo limit 1),
         (select p.id from productos p where regexp_replace(translate(lower(p.nombre), 'áéíóúüñàèìòùâêîôû', 'aeiouunaeiouaeiou'), '[^a-z0-9]', '', 'g') = a.clave
           order by p.created_at limit 1)
       ) as producto_id
from _archivo a;

create temp table _resumen (concepto text, cantidad int) on commit preserve rows;

insert into _resumen
select 'Existentes que ya tenían ese código (sin cambios)', count(*)
from _cruce c join productos p on p.id = c.producto_id where p.codigo_barras = c.codigo;

-- 1) Existentes: actualizar el código si cambió y nadie más lo usa.
with cambios as (
  update productos p
  set codigo_barras = c.codigo
  from _cruce c
  where c.producto_id = p.id
    and p.codigo_barras is distinct from c.codigo
    and not exists (select 1 from productos o where o.codigo_barras = c.codigo and o.id <> p.id)
  returning p.id
)
insert into _resumen select 'Productos existentes con código actualizado', count(*) from cambios;

-- 2) Nuevos: crear con precio y costo en 0.
with nuevos as (
  insert into productos (id, nombre, codigo_barras, precio_venta, costo_actual, activo, es_favorito, es_precio_fijo)
  select gen_random_uuid(), c.nombre, c.codigo, 0, 0, true, false, false
  from _cruce c
  where c.producto_id is null
  returning id, codigo_barras
),
ligados as (
  update _cruce c set producto_id = n.id from nuevos n where c.codigo = n.codigo_barras returning 1
)
insert into _resumen select 'Productos nuevos creados (precio y costo en 0)', (select count(*) from nuevos);

-- 3) Inventario: renglón con stock 0 en cada tienda para los importados que no tengan.
with inv as (
  insert into inventario_tienda (id, tienda_id, producto_id, stock_actual)
  select gen_random_uuid(), t.id, c.producto_id, 0
  from (select distinct producto_id from _cruce where producto_id is not null) c
  cross join tiendas t
  where not exists (
    select 1 from inventario_tienda i where i.tienda_id = t.id and i.producto_id = c.producto_id
  )
  returning 1
)
insert into _resumen select 'Renglones nuevos en inventario_tienda (stock 0)', count(*) from inv;

insert into _resumen
select 'Códigos del archivo que ya usaba otro producto (no se cambiaron)', count(*)
from _cruce c join productos p on p.id = c.producto_id
where p.codigo_barras is distinct from c.codigo;

commit;

select concepto, cantidad from _resumen;
